#!/usr/bin/env node
/**
 * Generate `cordis.patch.yml` from `presets/omnigate-models.json`.
 *
 * The preset JSON is the single source of truth shipped to users. The bundle
 * patch installs the two OmniGate routes immediately (so the Models page only
 * asks for an API key) and inserts the host row that serves the preset and the
 * quota widget. The same JSON is fetched from jsDelivr at runtime, so model
 * updates reach an installed route without reinstalling the plugin.
 */

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { toProviders, validatePreset } from "../lib/preset.js";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const presetPath = join(root, "presets", "omnigate-models.json");
const patchPath = join(root, "cordis.patch.yml");

/** JSON string literals are valid YAML double-quoted scalars. */
const quote = (value) => JSON.stringify(value);

const parsed = JSON.parse(readFileSync(presetPath, "utf8"));
const valid = validatePreset(parsed);
const providers = toProviders(valid);
const routeIds = Object.keys(providers);

/** Emit one model entry at the given indentation. */
function emitModel(model, indent) {
  const pad = " ".repeat(indent);
  const lines = [
    `${pad}- id: ${quote(model.id)}`,
    `${pad}  name: ${quote(model.name)}`,
    `${pad}  contextWindow: ${model.contextWindow}`,
    `${pad}  maxTokens: ${model.maxTokens}`,
    `${pad}  input: [${model.input.map(quote).join(", ")}]`,
    `${pad}  reasoningEfforts:`,
  ];
  for (const [level, wire] of Object.entries(model.reasoningEfforts)) {
    lines.push(`${pad}    ${level}: ${wire === null ? "null" : quote(wire)}`);
  }
  if (model.compat !== undefined && Object.keys(model.compat).length > 0) {
    lines.push(`${pad}  compat:`);
    for (const [key, value] of Object.entries(model.compat)) {
      lines.push(`${pad}    ${key}: ${typeof value === "string" ? quote(value) : String(value)}`);
    }
  }
  return lines.join("\n");
}

const patch = [
  "# Generated by scripts/build-preset.mjs from presets/omnigate-models.json.",
  "# Do not edit this file by hand: edit the preset JSON and run `npm run build:preset`.",
  "#",
  "# 1) Preinstall the two OmniGate routes so the Models page only needs an API key.",
  "#    The host plugin keeps these routes in sync with the jsDelivr preset.",
  "- id: llm-pi-ai",
  '  name: "@deepseek-ai/dsh-llm-pi-ai"',
  "  config:",
  "    providers:",
];

for (const route of routeIds) {
  patch.push(`      ${route}:`);
  patch.push(`        displayName: ${quote(providers[route].displayName)}`);
  patch.push(`        apiKeyEnv: ${quote(providers[route].apiKeyEnv)}`);
  patch.push(`        api: ${quote(providers[route].api)}`);
  patch.push(`        baseURL: ${quote(providers[route].baseURL)}`);
  patch.push("        models:");
  for (const model of providers[route].models) patch.push(emitModel(model, 10));
}

patch.push("");
patch.push("# 2) Insert this plugin's host row: preset sync, directory entry, quota widget.");
patch.push("- insert:");
patch.push("    - id: omnigate");
patch.push('      name: "dsh-omnigate"');
patch.push("      config:");
patch.push('        baseURL: "https://gate.oky.su/v1"');
patch.push(`        apiKeyEnv: ${quote(parsed.apiKeyEnv)}`);
patch.push('        presetURL: "https://cdn.jsdelivr.net/gh/Okysu/dsh-omnigate@main/presets/omnigate-models.json"');
patch.push('        presetFallbackURL: "https://raw.githubusercontent.com/Okysu/dsh-omnigate/main/presets/omnigate-models.json"');
patch.push("        cacheSeconds: 15");
patch.push("        timeoutMs: 20000");
patch.push("        syncPreset: true");

writeFileSync(patchPath, `${patch.join("\n")}\n`, "utf8");

console.log(`[build-preset] wrote ${patchPath}`);
for (const route of routeIds) {
  console.log(`[build-preset]   ${route}: ${providers[route].models.length} models`);
}
console.log(`[build-preset] ${parsed.models.length} models total, ${routeIds.length} routes`);
